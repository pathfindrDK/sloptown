"""Generate palettes/<id>.css from catalog.json (stdlib only).

    python3 template-design/build.py           write the files
    python3 template-design/build.py --check   exit 1 if a file is missing or stale

A palette file sets neutral --palette-* properties (light, and dark under
[data-theme="dark"]); each style's design.css maps them onto its framework.
Every colour comes as hex, "r, g, b" (-rgb) and h/s/l (-h, -s, -l), because the
frameworks want different forms (Bootstrap rgb, Bulma hsl).
"""

import colorsys
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROLES = ["primary", "onPrimary", "bg", "surface", "text", "muted", "border"]
# Text pairs that must stay readable (WCAG AA for normal text).
CONTRAST = [("onPrimary", "primary"), ("text", "bg"), ("text", "surface"), ("muted", "surface")]
MIN_CONTRAST = 4.5


def load() -> dict:
    return json.loads((HERE / "catalog.json").read_text())


def rgb(hex_: str) -> tuple[int, int, int]:
    h = hex_.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def luminance(hex_: str) -> float:
    def ch(c: int) -> float:
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = rgb(hex_)
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def kebab(role: str) -> str:
    return "".join("-" + c.lower() if c.isupper() else c for c in role)


def props(colours: dict[str, str]) -> list[str]:
    out = []
    for role in ROLES:
        hex_ = colours[role].lower()
        r, g, b = rgb(hex_)
        h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
        name = f"--palette-{kebab(role)}"
        out += [
            f"  {name}: {hex_};",
            f"  {name}-rgb: {r}, {g}, {b};",
            f"  {name}-h: {round(h * 360)}deg;",
            f"  {name}-s: {round(s * 100)}%;",
            f"  {name}-l: {round(l * 100)}%;",
        ]
    return out


def render(palette: dict) -> str:
    return "\n".join([
        f"/* Platform-owned (locked): the \"{palette['name']['da']}\" palette. The teacher changes it under",
        "   Indstillinger; generated by template-design/build.py, do not edit. */",
        ":root {",
        "  color-scheme: light;",
        *props(palette["light"]),
        "}",
        ':root[data-theme="dark"] {',
        "  color-scheme: dark;",
        *props(palette["dark"]),
        "}",
        "",
    ])


def problems(catalog: dict) -> list[str]:
    out = []
    for p in catalog["palettes"]:
        for mode in ("light", "dark"):
            missing = [r for r in ROLES if r not in p[mode]]
            if missing:
                out.append(f"{p['id']} {mode}: missing {missing}")
                continue
            for fg, bg in CONTRAST:
                c = contrast(p[mode][fg], p[mode][bg])
                if c < MIN_CONTRAST:
                    out.append(f"{p['id']} {mode}: {fg} on {bg} is {c:.2f}:1 (< {MIN_CONTRAST})")
    return out


def main(check: bool) -> int:
    catalog = load()
    if errs := problems(catalog):
        print("\n".join(errs), file=sys.stderr)
        return 1
    stale = []
    (HERE / "palettes").mkdir(exist_ok=True)
    for p in catalog["palettes"]:
        path = HERE / "palettes" / f"{p['id']}.css"
        text = render(p)
        if path.exists() and path.read_text() == text:
            continue
        if check:
            stale.append(str(path.relative_to(HERE)))
        else:
            path.write_text(text)
    if stale:
        print(f"stale: {', '.join(stale)} (run template-design/build.py)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))
